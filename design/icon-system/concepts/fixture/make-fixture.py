# report: on-screen count + near overlaps (<22px)
for k in FRAMES:
  on=[e for e in out["places"] if e["pos"][k] and not e["pos"].get(k+"Clustered")]
  print(k,"solo on screen:",len(on),"clusters:",[(c["members"],c["anyStarred"]) for c in out["clusters"][k]])
